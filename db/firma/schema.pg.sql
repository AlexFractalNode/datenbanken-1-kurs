-- Beispieldatenbank Firma, DDL fuer PostgreSQL (PGlite im Playground).
-- Entspricht schema.sql (Firebird 3). Abweichung: BLOB SUB_TYPE TEXT -> TEXT.
-- Identity-Spalten, Domaenen und FK-Aktionen sind gleich formuliert.

-- Domaenen ------------------------------------------------------------------

CREATE DOMAIN d_gehalt AS NUMERIC(9,2) CHECK (VALUE > 0);
CREATE DOMAIN d_stunden AS NUMERIC(6,1) CHECK (VALUE >= 0);

-- Leitung (1:1): abteilung.leiter_id ist UNIQUE. Der Fremdschluessel wird
-- erst nach mitarbeiter angelegt, weil beide Tabellen aufeinander verweisen.
CREATE TABLE abteilung (
    abteilung_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung   VARCHAR(40) NOT NULL UNIQUE,
    standort      VARCHAR(30) NOT NULL,
    leiter_id     INTEGER UNIQUE
);

-- Vorgesetzter (rekursiv): vorgesetzter_id verweist auf mitarbeiter
CREATE TABLE mitarbeiter (
    mitarbeiter_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorname         VARCHAR(30) NOT NULL,
    nachname        VARCHAR(30) NOT NULL,
    email           VARCHAR(60) NOT NULL UNIQUE,
    eintritt        DATE NOT NULL,
    gehalt          d_gehalt NOT NULL,     -- monatlich, brutto
    provision       NUMERIC(7,2),          -- nur im Vertrieb, sonst NULL
    abteilung_id    INTEGER REFERENCES abteilung (abteilung_id) ON DELETE SET NULL,
    vorgesetzter_id INTEGER REFERENCES mitarbeiter (mitarbeiter_id) ON DELETE SET NULL,
    CHECK (vorgesetzter_id <> mitarbeiter_id)
);

ALTER TABLE abteilung ADD CONSTRAINT fk_abteilung_leiter
    FOREIGN KEY (leiter_id) REFERENCES mitarbeiter (mitarbeiter_id) ON DELETE SET NULL;

CREATE TABLE projekt (
    projekt_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titel         VARCHAR(60) NOT NULL UNIQUE,
    abteilung_id  INTEGER NOT NULL REFERENCES abteilung (abteilung_id),
    startdatum    DATE NOT NULL,
    enddatum      DATE,                    -- NULL = laeuft noch
    budget        NUMERIC(12,2),           -- NULL = noch nicht festgelegt
    beschreibung  TEXT,
    CHECK (enddatum IS NULL OR enddatum >= startdatum)
);

-- m:n zwischen mitarbeiter und projekt mit Stunden
CREATE TABLE mitarbeit (
    mitarbeiter_id  INTEGER NOT NULL REFERENCES mitarbeiter (mitarbeiter_id) ON DELETE CASCADE,
    projekt_id      INTEGER NOT NULL REFERENCES projekt (projekt_id) ON DELETE CASCADE,
    stunden         d_stunden NOT NULL,
    rolle           VARCHAR(20),
    PRIMARY KEY (mitarbeiter_id, projekt_id)
);
