/**
 * Hints for Firebird syntax in the PostgreSQL playground (spec §13, db/DIALECT-NOTES.md).
 *
 * The tasks show the Firebird solution, the playground runs PostgreSQL (PGlite). When a statement
 * fails and its text contains a typical Firebird construct, `hint` names the PostgreSQL equivalent.
 * Detection looks at the SQL (without strings and comments), not at the wording of the error message,
 * because PostgreSQL reports most of these only as a generic syntax error.
 */

/** Removes comments and the content of string literals, so keywords inside them do not count. */
export function stripSql(sql: string): string {
  return sql
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/--[^\n]*/g, ' ')
    .replace(/'(?:[^']|'')*'/g, "''");
}

interface Rule {
  test: RegExp;
  text: (m: RegExpExecArray) => string;
}

const RULES: Rule[] = [
  {
    // SELECT [DISTINCT] FIRST n [SKIP m]
    test: /\bselect\s+(?:distinct\s+)?first\s+(\d+)(?:\s+skip\s+(\d+))?/i,
    text: (m) =>
      `FIRST ${m[1]}${m[2] ? ` SKIP ${m[2]}` : ''} ist Firebird-Syntax. In PostgreSQL steht die Begrenzung am Ende der Abfrage: ` +
      `\`LIMIT ${m[1]}${m[2] ? ` OFFSET ${m[2]}` : ''}\` oder standardnah ` +
      `\`${m[2] ? `OFFSET ${m[2]} ROWS ` : ''}FETCH FIRST ${m[1]} ROWS ONLY\`.`,
  },
  {
    test: /\bskip\s+(\d+)/i,
    text: (m) => `SKIP ${m[1]} gibt es nur in Firebird. In PostgreSQL überspringst du Zeilen mit \`OFFSET ${m[1]} ROWS\` am Ende der Abfrage.`,
  },
  {
    // ROWS m [TO n] at the end of a statement
    test: /\brows\s+(\d+)(?:\s+to\s+(\d+))?\s*(?:;|$)/i,
    text: (m) => {
      const from = Number(m[1]);
      if (m[2] === undefined) return `ROWS ${from} ist Firebird-Syntax. In PostgreSQL schreibst du \`LIMIT ${from}\`.`;
      const to = Number(m[2]);
      return (
        `ROWS ${from} TO ${to} ist Firebird-Syntax. In PostgreSQL schreibst du \`LIMIT ${to - from + 1} OFFSET ${from - 1}\` ` +
        `(Zeilen ${from} bis ${to}).`
      );
    },
  },
  {
    test: /\bgen_id\s*\(/i,
    text: () =>
      'GEN_ID(...) ist ein Firebird-Generator. In PostgreSQL nimmst du eine Identity-Spalte ' +
      '(`GENERATED BY DEFAULT AS IDENTITY`, der Wert wird beim INSERT vergeben) oder eine Sequenz: ' +
      "`CREATE SEQUENCE name;` und `nextval('name')`.",
  },
  {
    test: /\bnext\s+value\s+for\s+([a-z_][\w$]*)/i,
    text: (m) => `NEXT VALUE FOR ${m[1]} ist Firebird-Syntax. In PostgreSQL liefert \`nextval('${m[1]}')\` den nächsten Sequenzwert.`,
  },
  {
    test: /\b(?:create|alter|drop)\s+generator\b|\bset\s+generator\b/i,
    text: () =>
      'Generatoren heißen in PostgreSQL Sequenzen: `CREATE SEQUENCE name;`, `setval(\'name\', wert)`. ' +
      'Für Schlüsselspalten ist eine Identity-Spalte meist einfacher.',
  },
  {
    test: /\brdb\$database\b/i,
    text: () =>
      'RDB$DATABASE ist eine Firebird-Systemtabelle, die man für SELECT ohne Tabelle braucht. PostgreSQL kommt ohne FROM aus: `SELECT 1;`.',
  },
  {
    test: /\brdb\$\w+/i,
    text: () =>
      'RDB$-Tabellen sind Firebird-Systemtabellen. Die Metadaten von PostgreSQL findest du im `information_schema` ' +
      '(z. B. `information_schema.tables`, `information_schema.columns`).',
  },
  {
    test: /\blist\s*\(/i,
    text: () => "LIST(spalte, ', ') ist Firebird. In PostgreSQL heißt die Funktion `STRING_AGG(spalte, ', ')`.",
  },
  {
    test: /\bcontaining\b/i,
    text: () => "CONTAINING ist Firebird-Syntax. In PostgreSQL schreibst du `spalte ILIKE '%text%'` (ohne Groß-/Kleinschreibung) oder `LIKE '%text%'`.",
  },
  {
    test: /\bdate(?:add|diff)\s*\(/i,
    text: () =>
      "DATEADD/DATEDIFF gibt es in PostgreSQL nicht. Tage addierst du mit `datum + 1` oder `datum + INTERVAL '1 month'`, " +
      'Tage zwischen zwei Daten ergibt `datum2 - datum1`.',
  },
  {
    test: /\bextract\s*\(\s*(?:weekday|yearday)\b/i,
    text: () => 'In PostgreSQL heißen die Felder `DOW` (Wochentag, 0 = Sonntag) und `DOY` (Tag im Jahr, der 1. Januar ist 1): `EXTRACT(DOW FROM datum)`.',
  },
  {
    test: /\biif\s*\(/i,
    text: () => 'IIF(bedingung, a, b) gibt es in PostgreSQL nicht. Nimm `CASE WHEN bedingung THEN a ELSE b END`.',
  },
  {
    test: /\bdecode\s*\(/i,
    text: () => 'DECODE ist Firebird-Syntax. In PostgreSQL schreibst du `CASE ausdruck WHEN wert THEN ergebnis ... END`.',
  },
  {
    test: /\bexecute\s+block\b|\bset\s+term\b/i,
    text: () =>
      'SET TERM und EXECUTE BLOCK gehören zu PSQL, der Prozedursprache von Firebird. Im Playground genügen einzelne SQL-Anweisungen ' +
      'mit `;`. Trigger und Prozeduren laufen nur in Firebird (bei PostgreSQL wäre es PL/pgSQL).',
  },
  {
    test: /\bblob\s+sub_type\b/i,
    text: () => 'BLOB SUB_TYPE TEXT ist Firebird. In PostgreSQL nimmst du `TEXT` für langen Text.',
  },
  {
    test: /\brecreate\s+(?:table|view|procedure|trigger)\b/i,
    text: () => 'RECREATE gibt es nur in Firebird. In PostgreSQL: `DROP TABLE IF EXISTS name;` und danach `CREATE TABLE name (...)`.',
  },
  {
    test: /\balter\s+column\s+[\w"$]+\s+to\s+[\w"$]+/i,
    text: () => 'Spalten benennst du in PostgreSQL so um: `ALTER TABLE tabelle RENAME COLUMN alt TO neu;` (Firebird: `ALTER COLUMN alt TO neu`).',
  },
  {
    test: /\bupdate\s+or\s+insert\b/i,
    text: () => 'UPDATE OR INSERT ist Firebird. In PostgreSQL schreibst du `INSERT ... ON CONFLICT (schluessel) DO UPDATE SET ...`.',
  },
];

/**
 * PostgreSQL equivalent for Firebird syntax in `sql`, or null.
 * Only used for failed statements: without an error message the result is null.
 */
export function hint(errorMsg: string, sql: string): string | null {
  if (errorMsg.trim() === '') return null;
  const text = stripSql(sql);
  for (const rule of RULES) {
    const m = rule.test.exec(text);
    if (m) return rule.text(m);
  }
  return null;
}
