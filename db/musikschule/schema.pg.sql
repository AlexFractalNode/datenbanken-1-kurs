-- Beispieldatenbank Musikschule, DDL fuer PostgreSQL (PGlite im Playground).
-- Entspricht schema.sql (Firebird 3). Abweichung: BLOB SUB_TYPE TEXT -> TEXT.
-- Identity-Spalten, Domaenen, BOOLEAN und FK-Aktionen sind gleich formuliert.

-- Domaenen ------------------------------------------------------------------

CREATE DOMAIN d_betrag AS NUMERIC(8,2) CHECK (VALUE >= 0);
CREATE DOMAIN d_niveau AS VARCHAR(16) CHECK (VALUE IN ('Anfaenger', 'Mittelstufe', 'Fortgeschritten'));

-- Generalisierung: person ist Supertyp, lehrkraft und schueler sind Subtypen
-- (je eine eigene Tabelle, Primaerschluessel = Fremdschluessel auf person).
-- Die Generalisierung ist nicht disjunkt und nicht total: eine Person kann
-- beides sein oder keines von beiden.

CREATE TABLE person (
    person_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorname       VARCHAR(30) NOT NULL,
    nachname      VARCHAR(30) NOT NULL,
    geburtsdatum  DATE,
    email         VARCHAR(60) UNIQUE,
    telefon       VARCHAR(20),
    ort           VARCHAR(30) NOT NULL
);

CREATE TABLE instrument (
    instrument_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung   VARCHAR(30) NOT NULL UNIQUE,
    familie       VARCHAR(20) NOT NULL
                  CHECK (familie IN ('Tasten', 'Streich', 'Zupf', 'Blas', 'Schlag')),
    leihgebuehr   d_betrag     -- monatlich; NULL = nicht ausleihbar
);

CREATE TABLE raum (
    raum_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung   VARCHAR(20) NOT NULL UNIQUE,
    etage         SMALLINT NOT NULL,
    plaetze       SMALLINT NOT NULL CHECK (plaetze > 0),
    hat_klavier   BOOLEAN DEFAULT FALSE NOT NULL
);

CREATE TABLE lehrkraft (
    person_id          INTEGER NOT NULL PRIMARY KEY
                       REFERENCES person (person_id) ON DELETE CASCADE,
    eingestellt_am     DATE NOT NULL,
    stundensatz        d_betrag NOT NULL,
    hauptinstrument_id INTEGER
                       REFERENCES instrument (instrument_id) ON DELETE SET NULL
);

CREATE TABLE schueler (
    person_id     INTEGER NOT NULL PRIMARY KEY
                  REFERENCES person (person_id) ON DELETE CASCADE,
    eintritt      DATE NOT NULL,
    ermaessigt    BOOLEAN DEFAULT FALSE NOT NULL
);

CREATE TABLE kurs (
    kurs_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titel          VARCHAR(60) NOT NULL,
    instrument_id  INTEGER REFERENCES instrument (instrument_id) ON DELETE SET NULL,
    lehrkraft_id   INTEGER NOT NULL REFERENCES lehrkraft (person_id),
    raum_id        INTEGER REFERENCES raum (raum_id) ON DELETE SET NULL,
    niveau         d_niveau NOT NULL,
    max_teilnehmer SMALLINT NOT NULL CHECK (max_teilnehmer > 0),
    gebuehr_monat  d_betrag NOT NULL,
    startdatum     DATE NOT NULL,
    enddatum       DATE,
    beschreibung   TEXT,
    CHECK (enddatum IS NULL OR enddatum >= startdatum)
);

-- m:n zwischen schueler und kurs mit eigenen Attributen
CREATE TABLE belegung (
    schueler_id    INTEGER NOT NULL REFERENCES schueler (person_id) ON DELETE CASCADE,
    kurs_id        INTEGER NOT NULL REFERENCES kurs (kurs_id) ON DELETE CASCADE,
    angemeldet_am  DATE NOT NULL,
    abgemeldet_am  DATE,
    rabatt_prozent SMALLINT DEFAULT 0 NOT NULL CHECK (rabatt_prozent BETWEEN 0 AND 50),
    PRIMARY KEY (schueler_id, kurs_id),
    CHECK (abgemeldet_am IS NULL OR abgemeldet_am >= angemeldet_am)
);

-- Unterrichtstermin; raum_id NULL = Raum des Kurses
CREATE TABLE termin (
    termin_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kurs_id       INTEGER NOT NULL REFERENCES kurs (kurs_id) ON DELETE CASCADE,
    datum         DATE NOT NULL,
    uhrzeit       TIME NOT NULL,
    dauer_min     SMALLINT NOT NULL CHECK (dauer_min > 0),
    raum_id       INTEGER REFERENCES raum (raum_id) ON DELETE SET NULL,
    ausgefallen   BOOLEAN DEFAULT FALSE NOT NULL,
    UNIQUE (kurs_id, datum, uhrzeit)
);

CREATE TABLE ausleihe (
    ausleihe_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id INTEGER NOT NULL REFERENCES instrument (instrument_id),
    schueler_id   INTEGER NOT NULL REFERENCES schueler (person_id),
    inventar_nr   CHAR(8) NOT NULL,
    ausgabe       DATE NOT NULL,
    rueckgabe     DATE,        -- NULL = noch ausgeliehen
    CHECK (rueckgabe IS NULL OR rueckgabe >= ausgabe)
);

-- rekursive Beziehung: eine Lehrkraft vertritt eine andere im Zeitraum von..bis
CREATE TABLE vertretung (
    vertretung_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lehrkraft_id  INTEGER NOT NULL REFERENCES lehrkraft (person_id) ON DELETE CASCADE,
    vertreter_id  INTEGER NOT NULL REFERENCES lehrkraft (person_id) ON DELETE CASCADE,
    von           DATE NOT NULL,
    bis           DATE NOT NULL,
    grund         VARCHAR(40),
    UNIQUE (lehrkraft_id, vertreter_id, von),
    CHECK (vertreter_id <> lehrkraft_id),
    CHECK (bis >= von)
);

-- Zahlung fuer einen Kurs oder eine Ausleihe; bezahlt_am NULL = offen
CREATE TABLE zahlung (
    zahlung_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schueler_id   INTEGER NOT NULL REFERENCES schueler (person_id) ON DELETE CASCADE,
    kurs_id       INTEGER REFERENCES kurs (kurs_id) ON DELETE SET NULL,
    ausleihe_id   INTEGER REFERENCES ausleihe (ausleihe_id) ON DELETE SET NULL,
    betrag        d_betrag NOT NULL,
    faellig_am    DATE NOT NULL,
    bezahlt_am    DATE,
    zahlungsart   VARCHAR(12)
                  CHECK (zahlungsart IN ('Ueberweisung', 'Lastschrift', 'Bar')),
    CHECK (kurs_id IS NULL OR ausleihe_id IS NULL)
);
